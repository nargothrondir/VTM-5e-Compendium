"""Нормализация текста, извлечённого из книг правил.

Артефактов ровно три, и все они чинятся без ИИ:
  * NBSP (\xa0) и прочие невидимые пробелы;
  * мягкие переносы на конце строки (в STV501 это U+2011, местами обычный дефис);
  * маркер списка, который выводится как латинская `n` (символ Wingdings).
"""

import re

# Дефисы, которыми книга разрывает СЛОВО на переносе: обычный дефис-минус,
# мягкий перенос, дефис и неразрывный дефис. Длинное и среднее тире сюда
# не входят: в конце строки это полноценная пунктуация («грозным — как
# правило»), и склейка по ним слепляла бы соседние слова.
HYPHENS = "-­‐‑"

# Невидимые пробелы: NBSP, узкий неразрывный, тонкий, волосяной, zero-width.
INVISIBLE_SPACES = "      ﻿​"

# Маркер списка. В шрифте книги это залитый квадрат, но в текстовый слой
# он попадает как одинокая `n` в начале строки — иногда с ведущим пробелом.
BULLET_RE = re.compile(r"^[ \t]*n(?=[  ])", re.M)

# Колонтитул: разрядка капсом («П е Р С о н а ж и») плюс номер страницы.
RUNNING_HEAD_RE = re.compile(
    r"^\s*(?:\d[\d\s]*)?(?:[А-ЯЁа-яё]\s){2,}[А-ЯЁа-яё]\s*(?:\d[\d\s]*)?\s*$", re.M
)

# Сноска-ссылка на перевод терминов: «1 Прим. пер.: velocitas (лат.) — …».
TRANSLATOR_NOTE_RE = re.compile(r"^\s*\d+\s*\nПрим\. пер\.:.*?$", re.M | re.S)


# Кириллица, прочитанная как Latin-1: «Ãàíãðåë» вместо «Гангрел». Так выходит,
# когда у шрифта нет таблицы ToUnicode и байты CP1251 читаются побайтово.
MOJIBAKE_RE = re.compile(r"[À-ÿ]+")
CYRILLIC_RE = re.compile(r"[а-яёА-ЯЁ]")


def fix_encoding(text: str) -> str:
    """Чинит кириллицу, выпавшую из PDF как Latin-1.

    Порча бывает и точечной — «Если â истории нет сцен», — поэтому внутри
    заведомо кириллического текста чинится прогон любой длины. Там, где
    кириллицы нет, порог выше: осмысленный латинский текст трогать нельзя.
    """
    if not text or not MOJIBAKE_RE.search(text):
        return text

    least = 1 if CYRILLIC_RE.search(text) else 3

    def repair(match):
        run = match.group(0)
        if len(run) < least:
            return run

        # Одиночный символ, приросший к кириллическому слову, — это знак
        # ударения из самой книги, а не порча: «Мавлá» так и набрано.
        # Порча одиночными буквами стоит отдельным словом: «Если â истории».
        if len(run) == 1:
            before = text[match.start() - 1] if match.start() else " "
            after = text[match.end()] if match.end() < len(text) else " "
            if CYRILLIC_RE.match(before) or CYRILLIC_RE.match(after):
                return run

        try:
            return run.encode("latin-1").decode("cp1251")
        except (UnicodeEncodeError, UnicodeDecodeError):
            return run

    return MOJIBAKE_RE.sub(repair, text)


def normalize(text: str) -> str:
    """Сырой текстовый слой -> связный текст в одну строку на абзац."""
    if not text:
        return ""

    text = fix_encoding(text)

    text = TRANSLATOR_NOTE_RE.sub("", text)

    for ch in INVISIBLE_SPACES:
        text = text.replace(ch, " ")

    # Маркер списка -> ■, до склейки строк: он всегда стоит в начале строки.
    text = BULLET_RE.sub("■", text)

    text = RUNNING_HEAD_RE.sub("", text)

    # Пустая строка — граница абзаца, проставленная по границе блока PDF.
    # Прячем её, чтобы не потерять при схлопывании остальных переводов строк.
    text = re.sub(r"\n[ \t]*\n[\s]*", "\x00", text)

    # Склейка переносов: дефис + перевод строки + отступ следующей строки.
    # Именно здесь рождалось «до ма» / «под обной» при копировании мышью.
    text = re.sub(rf"[{HYPHENS}]\s*\n\s*", "", text)

    # Оставшиеся переводы строк внутри абзаца — это вёрстка по ширине колонки,
    # а не границы абзацев.
    text = re.sub(r"\s*\n\s*", " ", text)

    text = re.sub(r"\s*\x00\s*", "\n", text)
    text = re.sub(r"[ \t]{2,}", " ", text)
    return text.strip()


def split_paragraphs(text: str) -> list[str]:
    """Режет нормализованный текст на абзацы: по границам блоков и маркерам."""
    parts = re.split(r"\n|(?=■)", text)
    return [p.strip() for p in parts if p.strip()]


# --- типографика записи ---------------------------------------------------
#
# Книга набирает подписи параметров и игровые термины теми же начертаниями,
# что и прозу: на полосе их разводит вёрстка. В карточке Foundry вёрстки нет,
# всё сливается в один кегль, и «Пул: смекалка + упорство» глазами не
# вылавливается. Возвращаем различение начертанием — текст при этом не
# меняется ни на букву.

# Подписи блоков. В регулярку идут отсортированными по длине: иначе «Пулы
# кубиков» разрезалось бы по «Пул», а порядок в списке — вещь, которую легко
# нарушить при следующем пополнении.
PARAM_LABELS = [
    "Расплата за активацию", "Добавить специализацию", "Необходимые условия",
    "Необходимая сила", "Продолжительность", "Пулы кубиков", "Пул кубиков",
    "Ингредиенты", "Длительность", "Компоненты", "Стоимость", "Требование",
    "Недостаток", "Амальгами", "Амальгама", "Расплата", "Система", "Процесс",
    "Правила", "Ритуал", "Пул",
    # Ступени исхода броска, метод алхимии и статы снаряжения: подписи по
    # существу, хотя в общий набор Дисциплин они не входят.
    "Получите достоинство", "Получить достоинство", "Перераспределение",
    "Атанор корпорис", "Кальцинация", "Поражение", "Внешность", "Триумф",
    "Победа", "Оружие", "Броня", "Успех",
]

# Подписи, за которыми стоит термин или формула пула, а не проза. Остальные
# («Система», «Правила», «Процесс») ведут абзац на пару сотен слов —
# сплошной курсив там читался бы хуже прямого.
TERM_VALUE_LABELS = {
    "Амальгама", "Амальгами", "Длительность", "Добавить специализацию",
    "Ингредиенты", "Компоненты", "Необходимая сила", "Необходимые условия",
    "Продолжительность", "Пул", "Пул кубиков", "Пулы кубиков", "Расплата",
    "Расплата за активацию", "Стоимость", "Требование",
}

# Граница, за которой значение перестаёт быть термином. «Расплата» и
# «Длительность» местами разрастаются до трёхсот знаков — это уже проза.
VALUE_LIMIT = 80

LABEL_RE = re.compile(
    r"^(■\s*)?("
    + "|".join(sorted(PARAM_LABELS, key=len, reverse=True))
    + r")\s*:[ \t]*")

# Дисциплины во всех падежах. Курсивом выделяются только они: «Кровь»
# встречается полторы сотни раз, и разметка каждого вхождения превратилась
# бы в шум, от которого выделение перестаёт работать вовсе.
DISCIPLINES = [
    ("Анимализм", "а|у|ом|е|"), ("Величи", "е|я|ю|ем|и"),
    ("Доминировани", "е|я|ю|ем|и"), ("Метаморфоз", "ы|ам|ами|ах|"),
    ("Мощ", "ь|и|ью"), ("Обливион", "а|у|ом|е|"), ("Сокрыти", "е|я|ю|ем|и"),
    ("Стойкост", "ь|и|ью"), ("Стремительност", "ь|и|ью"),
    ("Ясновидени", "е|я|ю|ем|и"),
]
TERM_RE = re.compile(
    r"(?<![А-Яа-яЁё])(?:"
    + r"Кровав(?:ое|ого|ому|ым|ом)\s+чародейств(?:о|а|у|ом|е)|"
    + "|".join(f"{stem}(?:{ends})" for stem, ends in DISCIPLINES)
    + r")(?![А-Яа-яЁё])")


def _mark_terms(text: str) -> str:
    return TERM_RE.sub(lambda m: f"<em>{m.group(0)}</em>", text)


def _split_value(value: str) -> tuple[str, str]:
    """Термин и хвост: скобка и конец предложения курсиву не принадлежат."""
    head = re.match(r"[^.;(]*", value).group(0).rstrip()
    if not head or len(head) > VALUE_LIMIT:
        return "", value
    return head, value[len(head):]


def _emphasize_paragraph(inner: str) -> str:
    # Размеченный абзац не трогаем — так проход остаётся идемпотентным,
    # а пометка источника («<em>Источник: …</em>») не разбирается как подпись.
    if "<" in inner:
        return inner

    hit = LABEL_RE.match(inner)
    if not hit:
        return _mark_terms(inner)

    label = hit.group(2)
    value = inner[hit.end():]
    out = f"{hit.group(1) or ''}<strong>{label}:</strong> "
    if label in TERM_VALUE_LABELS:
        head, tail = _split_value(value)
        if head:
            return out + f"<em>{head}</em>" + _mark_terms(tail)
    return out + _mark_terms(value)


PARAGRAPH_RE = re.compile(r"<p>(.*?)</p>", re.S)


def emphasize(html: str) -> str:
    """Подпись параметра — полужирным, термин — курсивом. Идемпотентно."""
    return PARAGRAPH_RE.sub(
        lambda m: "<p>" + _emphasize_paragraph(m.group(1)) + "</p>", html or "")


def to_html(text: str) -> str:
    """Абзацы -> HTML в том же виде, в каком его хранит компендиум."""
    return emphasize("".join(f"<p>{p}</p>" for p in split_paragraphs(text)))


def strip_html(html: str) -> str:
    """HTML описания -> голый текст (для диффов и проверок)."""
    text = re.sub(r"<[^>]+>", "\n", html or "")
    for ch in INVISIBLE_SPACES:
        text = text.replace(ch, " ")
    return re.sub(r"\s+", " ", text).strip()


# Украинские буквы, которых нет в русском алфавите. Самый дешёвый
# и самый надёжный детектор непереведённого текста.
UKRAINIAN_ONLY = set("іїєґІЇЄҐ")


def has_ukrainian(text: str) -> bool:
    return bool(UKRAINIAN_ONLY & set(text or ""))
