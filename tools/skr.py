import re
import pyperclip

# 1. Забираем текст из буфера обмена
text = pyperclip.paste()

if text:
    print("--- ИСХОДНЫЙ ТЕКСТ ИЗ БУФЕРА ---")
    print(text)
    print("-" * 32)

    # Шаг 2. Заменяем все виды скрытых и неразрывных пробелов на обычные
    text = text.replace("\xa0", " ")

    # Шаг 3. Точечно склеиваем переносы строк.
    # Если в конце строки стоит дефис (или любой похожий знак), а затем идет
    # перенос строки и, возможно, пробелы на новой строке — удаляем дефис и пробелы.
    # [-\u00ad\u2010-\u2015] — это перебор всех возможных видов дефисов и тире
    text = re.sub(r"[-\u00ad\u2010-\u2015\u2011]\s*\n\s*", "", text)

    # Шаг 4. Теперь, когда переносы слов склеены, превращаем оставшиеся
    # одиночные переносы строк (между обычными словами) в пробелы
    text = text.replace("\n", " ").replace("\r", " ")

    # Шаг 5. Схлопываем множественные пробелы в один
    text = re.sub(r" +", " ", text)
    text = text.strip()

    # 6. Возвращаем чистый текст в буфер обмена
    pyperclip.copy(text)

    print("\n--- ОБРАБОТАННЫЙ ТЕКСТ (УЖЕ В БУФЕРЕ ОБМЕНА) ---")
    print(text)
    print("-" * 48)
    print("Готово! Если результат устраивает, просто нажмите Ctrl+V в нужном месте.")
else:
    print("Буфер обмена пуст! Сначала скопируйте текст из PDF.")